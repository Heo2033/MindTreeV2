/// Порог уровня знаний, ниже которого действует антижаргон.
const int kNonExpertLevel = 2;

/// Основы для проверки: [level] — целевой уровень пользователя.
///
/// Для `level <= [kNonExpertLevel]` жёсткий список и список «на грани» дают
/// нарушения. Для экспертного уровня остаётся только жёсткий список.
List<String> activeJargonStems(int level) {
  final stems = <String>[...russianJargonStems, ...latinTermStems];
  if (level <= kNonExpertLevel) stems.addAll(borderlineStems);
  return stems
      .map((s) => s.toLowerCase())
      .toSet()
      .toList(growable: false)
    ..sort();
}

/// Находит термины жаргона в [text].
///
/// Возвращает уникальные срабатывания в порядке первого появления.
/// Словоформы склеиваются по падежам: основа `инвариант` ловит
/// «инварианта», «инварианты», «инвариантов».
///
/// Латинские термины срабатывают только целиком, а не по префиксу:
/// иначе `id` поймает «идея» в русском тексте и любой `ci` в «цифра».
List<String> findJargon(String text, int level) {
  if (text.isEmpty) return const [];
  final stems = activeJargonStems(level);
  final found = <String>[];

  for (final raw in text.split(_notWordChar)) {
    if (raw.isEmpty) continue;
    // Регистронезависимо, но в отчёте сохраняем исходное написание.
    final lower = raw.toLowerCase();

    for (final stem in stems) {
      final bool hit = stem.codeUnitAt(0) < _firstCyrillicCode
          // Латинская основа — только точное совпадение.
          ? lower == stem
          // Русская основа — по префиксу (падежные формы).
          : lower.startsWith(stem);
      if (hit) {
        if (!found.contains(raw)) found.add(raw);
        break;
      }
    }
  }

  return found;
}

/// Порог длины `one_liner` из инвариантов дерева знаний.
const int kOneLinerMaxLength = 120;

/// Порог длины `details` — согласован с промптами контента.
const int kDetailsMaxLength = 500;

/// `one_liner` длиннее лимита — нарушение контракта.
bool exceedsOneLinerLimit(String oneLiner) =>
    oneLiner.trim().length > kOneLinerMaxLength;
