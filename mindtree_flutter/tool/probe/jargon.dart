// Детектор жаргона для quality-проверок probe.
//
// Только детерминированный словарный поиск: никаких LLM, эмбеддингов и
// вероятностей. Словари собраны из типовых формулировок, которые LLM чаще
// всего тащит в объяснения для не-expert аудитории.
//
// Словоформы склеиваются по падежам: словарь хранит основу, а совпадение
// ищется по префиксу. Это детерминированно и не требует морфологии.

/// Разделители слов: всё, что НЕ является буквой русского или латинского
/// алфавита. Дефис и апостроф тоже считаются разделителями — иначе
/// `well-known` не матчился бы по `well`.
///
/// Намеренно используется negated-класс, а не `[0-9A-Za-zЀ-ӿ]`: в позитивном
/// классе диапазон кириллицы легко спутать с дефисом, а здесь риска нет.
final RegExp _notWordChar = RegExp('[^0-9A-Za-zЀ-ӿ]');

/// Код первой кириллической буквы: по нему отличаем русскую основу от
/// латинской (латиница матчится строго, кириллица — по префиксу).
const int _firstCyrillicCode = 0x0410;

