/// Порог правдоподобности одного замера времени, в миллисекундах (2 часа).
///
/// Выше порога замер — это уже не «медленно отвечал», а техническая находка:
/// либо сломанный таймер, когда момент старта не был заведён и в длительность
/// утекает абсолютное время (`now - 0` = epoch-мс ≈ 1.8e12 ≈ 20 суток), либо
/// сутки простоя приложения в фоне. Такую запись нельзя молча суммировать в
/// «время учёбы»: одна битая строка обнуляет Learning Gain / Time.
///
/// Константа намерально равна `kImplausibleAnswerMs` из тул ревью
/// (`tool/review/session_checks.dart`): тот же порог ловит уже записанное в
/// БД, этот — отсекает неправдоподобное до того, как оно попадёт в суммы
/// метрик. Значения держатся в паре — если меняется одно, меняется и другое.
///
/// Потребители в домене: фильтр сумм времени аналитики
/// (`analytics_service.dart`) и санитизация времени ответа перед записью
/// (`assessment_engine.dart::sanitizeAttemptTimeMs`) — attempt выше порога
/// аналитика всё равно выкинула бы из Learning Gain / Time.
const int kImplausibleDurationMs = 2 * 60 * 60 * 1000;
