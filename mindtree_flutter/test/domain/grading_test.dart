import 'package:flutter_test/flutter_test.dart';

import 'package:mindtree_flutter/domain/lib/grading.dart';

void main() {
  group('gradeOpenEnded', () {
    test('пустой ответ всегда неверен, даже при пустой рубрике', () {
      expect(gradeOpenEnded('', rubric: 'Объясни, что такое производная'), isFalse);
      expect(gradeOpenEnded('   ', rubric: ''), isFalse);
      expect(gradeOpenEnded('', rubric: ''), isFalse);
    });

    test('пустая рубрика — fallback: засчитываем любой непустой ответ', () {
      expect(gradeOpenEnded('Да', rubric: ''), isTrue);
      expect(gradeOpenEnded('Короткий ответ', rubric: ''), isTrue);
    });

    test('ответ с ключевыми терминами рубрики — верно (30% порог)', () {
      const rubric = 'Производная функции — предел отношения приращения функции '
          'к приращению аргумента.';
      expect(
        gradeOpenEnded('Производная функции это предел отношения приращений', rubric: rubric),
        isTrue,
      );
    });

    test('ответ без ключевых терминов — неверно', () {
      const rubric = 'Производная функции — предел отношения приращения функции '
          'к приращению аргумента.';
      expect(gradeOpenEnded('Ответ не по теме', rubric: rubric), isFalse);
    });

    test('слова короче 4 символов не считаются ключевыми', () {
      const rubric = 'Это проверка знаний.';
      // ключевые слова: "проверка", "знаний" (2 шт), порог 0.6 → нужно ≥1
      expect(gradeOpenEnded('это', rubric: rubric), isFalse); // "это" — не ключевое
      expect(gradeOpenEnded('проверка', rubric: rubric), isTrue);
    });

    test('пунктуация и регистр не мешают совпадению', () {
      const rubric = 'Митоз: деление клетки!';
      // ключевые слова: "митоз", "деление", "клетки" (3 шт), порог 0.9 → нужно ≥1
      expect(gradeOpenEnded('Митоз и деление клетки', rubric: rubric), isTrue);
    });

    test('рубрика без терминов (>3 символов) — fallback по длине ответа', () {
      const rubric = 'да нет!';
      // ключевых слов нет (все ≤3) → принимаем ответ длиннее 10 символов
      expect(gradeOpenEnded('короткий', rubric: rubric), isFalse);
      expect(gradeOpenEnded('достаточно длинный ответ на вопрос', rubric: rubric), isTrue);
    });

    // ── Регресс строгости грейдера ──────────────────────────────────────────
    // Прежний вариант сопоставлял только подстроку: «приращения» не
    // совпадало с «приращений», «клетки» — с «клетка», и содержательный
    // пересказ другими словоформами не проходил. Сопоставление по основе
    // слова (общий префикс ≥ 4) это лечит, порог 30% не меняется.

    test('морфология: содержательный ответ другими словоформами — верно', () {
      const rubric = 'Приращение функции и отношение приращений к аргументу.';
      // 5 терминов, порог 1.5 → нужно ≥2; старый вариант совпадал только
      // подстрокой «функции» (1 < 1.5) и давал ложный отказ, хотя ответ
      // называет все те же корни: приращени(я/й), относи(ть)-отношени(е),
      // аргумент(а/у).
      expect(
        gradeOpenEnded(
            'Изменения функции дают приращения относительно аргумента',
            rubric: rubric),
        isTrue,
      );
    });

    test('служебные слова рубрики не раздувают порог', () {
      const rubric = 'Митоз является процессом, при котором ядро клетки '
          'делится, и это можно назвать делением.';
      // Без служебных (является/можно): 8 терминов, порог 2.4 → нужно ≥3.
      // Ответ даёт три совпадения по основе: процесс(ом)↔процессе,
      // клетк(и)↔клетка, делится (подстрока).
      expect(
        gradeOpenEnded('В процессе клетка делится, образуя два новых ядра',
            rubric: rubric),
        isTrue,
      );
    });

    test('болтовня по-прежнему неверна, даже с ослабленным сопоставлением', () {
      const rubric = 'Производная функции — предел отношения приращения '
          'функции к приращению аргумента.';
      expect(
        gradeOpenEnded('Сегодня погода стояла отличная, я прогулялся в парке',
            rubric: rubric),
        isFalse,
      );
    });

    test('упоминание одного термина из длинной рубрики — не знание', () {
      const rubric = 'Митоз является процессом, при котором ядро клетки '
          'делится, и это можно назвать делением.';
      // 1 совпадение (ядро) из 8 при пороге 2.4 — name-dropping не проходит.
      expect(
        gradeOpenEnded('Я думаю, что тут ядро играет какую-то роль',
            rubric: rubric),
        isFalse,
      );
    });
  });
}