import 'dart:math';

/// Единый генератор коротких уникальных id-суффиксов (8 символов, base36).
///
/// Проблема, которую он закрывает: локальные `_shortId()` в движках строили
/// суффикс из хвоста timestamp + random и обрезали до 8 символов — при текущей
/// эпохе timestamp (12–13 знаков) случайный суффикс полностью отбрасывался,
/// и все id, созданные в один миллисекундный тик (один `.map()`/проход),
/// совпадали (`ci_`, `ms_`, `session_`, `assess_`, ...).
///
/// Гарантия уникальности ВНУТРИ одного процесса/прохода (даже при вызове
/// в один тик) — атомарный счётчик: 5 младших знаков из 8, до 60_466_176
/// значений подряд без повтора. Старшие 3 знака — случайные, чтобы снизить
/// коллизии с id из прошлых запусков (идемпотентные сценарии не требуют
/// межпроцессной детерминированности; запрещены лишь коллизии в одном вызове).
///
/// Изолят Dart однопоточный, поэтому top-level счётчик атомарен без lock'ов.
final Random _random = Random();
int _counter = _random.nextInt(60466176); // стартовая фаза 36^5

/// Уникальный 8-символьный суффикс (алфавит base36: 0-9a-z).
String shortId() {
  _counter = (_counter + 1) % 60466176; // 36^5
  final counterPart = _counter.toRadixString(36).padLeft(5, '0');
  final randomPart = _random.nextInt(46656).toRadixString(36).padLeft(3, '0'); // 36^3
  return '$randomPart$counterPart';
}

/// Готовый уникальный id с префиксом: `ci_`, `ms_`, `session_`, ...
/// Префикс сохраняется как есть, суффикс — ровно 8 символов base36.
String shortIdWith(String prefix) => '$prefix${shortId()}';